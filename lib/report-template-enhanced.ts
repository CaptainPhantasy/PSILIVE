function renderDetailedFindings(data: EnhancedReportData): string {
  const findings: Array<{
    type: string;
    items: Array<{ location: string; severity: string; type?: string; notes?: string }>;
  }> = [];

  if (data.rootIntrusion?.severity) {
    findings.push({
      type: "Root Intrusion",
      items: [{
        location: data.rootIntrusion.location || "Various locations",
        severity: data.rootIntrusion.severity,
        notes: data.rootIntrusion.notes,
      }],
    });
  }

  if (data.cracks?.length) {
    findings.push({ type: "Cracks", items: data.cracks });
  }
  if (data.bellies?.length) {
    findings.push({ type: "Bellies (Low Spots)", items: data.bellies });
  }
  if (data.offsetJoints?.length) {
    findings.push({ type: "Offset Joints", items: data.offsetJoints });
  }
  if (data.blockages?.length) {
    findings.push({ type: "Blockages", items: data.blockages.map((b) => ({ ...b, type: b.type })) });
  }

  const totalFindings = findings.reduce((sum, f) => sum + f.items.length, 0);

  // Build findings rows with optional video stills
  const findingsHTML = findings.length === 0
    ? `<div class="no-findings">
        <span class="no-findings-icon">✓</span>
        <span class="no-findings-text">No significant defects observed during inspection</span>
      </div>`
    : findings
        .map((finding) => {
          const itemRows = finding.items
            .map((item) => {
              // Find matching video still
              const still = data.videoStills?.find(
                (vs) => vs.title.toLowerCase().includes(finding.type.toLowerCase().split(" ")[0])
              );

              return `
              <div class="finding-item">
                ${still ? `
                <div class="finding-image-container">
                  <img src="${still.s3Url}" alt="${still.title}" class="finding-image" />
                  <span class="finding-image-timestamp">${formatTimestamp(still.timestamp)}</span>
                </div>` : ""}
                <div class="finding-details">
                  <div class="finding-meta">
                    <span class="finding-type-badge">${finding.type}</span>
                    <span class="finding-severity-badge" style="background-color: ${getSeverityColor(item.severity)}; color: white;">
                      ${formatSeverity(item.severity)}
                    </span>
                  </div>
                  <div class="finding-location">
                    <span class="location-label">Location:</span> ${item.location}
                  </div>
                  ${item.type ? `<div class="finding-subtype"><span class="location-label">Type:</span> ${item.type}</div>` : ""}
                  ${item.notes ? `<div class="finding-notes">${item.notes}</div>` : ""}
                </div>
              </div>`;
            })
            .join("");

          return itemRows;
        })
        .join("");

  return `
  <div class="section">
    <div class="section-header">
      <div class="section-icon">05</div>
      <h2 class="section-title">Detailed Findings</h2>
      <span class="findings-count">${totalFindings} finding${totalFindings !== 1 ? "s" : ""}</span>
    </div>
    <div class="findings-card">
      ${findingsHTML}
    </div>
    ${data.connectionToMain ? `
    <div class="connection-note">
      <span class="connection-label">Connection to Main Sewer:</span>
      <span class="connection-value">${data.connectionToMain}</span>
    </div>` : ""}
  </div>`;
}

