// ─── Helper Functions ────────────────────────────────────────────────────────

function getConditionColor(condition: string | null): string {
  switch (condition?.toUpperCase()) {
    case "EXCELLENT": return COLORS.excellent;
    case "GOOD": return COLORS.good;
    case "FAIR": return COLORS.fair;
    case "NEEDS_ATTENTION":
    case "POOR": return COLORS.poor;
    case "CRITICAL": return COLORS.critical;
    default: return COLORS.gray400;
  }
}

function getConditionLabel(condition: string | null): string {
  switch (condition?.toUpperCase()) {
    case "EXCELLENT": return "Excellent";
    case "GOOD": return "Good";
    case "FAIR": return "Fair";
    case "NEEDS_ATTENTION": return "Needs Attention";
    case "CRITICAL": return "Critical";
    default: return "Not Assessed";
  }
}

function getSeverityColor(severity: string): string {
  switch (severity?.toUpperCase()) {
    case "INFO": return COLORS.severityInfo;
    case "MINOR": return COLORS.severityMinor;
    case "MODERATE": return COLORS.severityModerate;
    case "MAJOR": return COLORS.severityMajor;
    case "CRITICAL": return COLORS.severityCritical;
    default: return COLORS.gray500;
  }
}

function formatSeverity(severity: string): string {
  if (!severity) return "Unknown";
  return severity.charAt(0).toUpperCase() + severity.slice(1).toLowerCase();
}

function formatMaterial(material: string | null): string {
  if (!material) return "Unknown";
  return material.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

function getUrgencyConfig(urgency: string | null): { label: string; color: string; bg: string } {
  switch (urgency?.toUpperCase()) {
    case "IMMEDIATE":
      return { label: "Priority Review", color: COLORS.white, bg: COLORS.amber600 };
    case "SOON":
      return { label: "Follow-Up Context", color: COLORS.white, bg: COLORS.blue };
    case "MONITOR":
      return { label: "Monitor Noted", color: COLORS.navy, bg: COLORS.amber100 };
    case "NONE":
      return { label: "No Immediate Observation", color: COLORS.white, bg: COLORS.navyLight };
    default:
      return { label: "Assessment Pending", color: COLORS.gray700, bg: COLORS.gray100 };
  }
}

function formatTimestamp(seconds: number): string {
  const mins = Math.floor(seconds / 60);
  const secs = seconds % 60;
  return `${mins}:${secs.toString().padStart(2, "0")}`;
}

